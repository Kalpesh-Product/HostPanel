function buildAttendanceLogTimeline(row: AttendanceMonthRow): { label: string; time: string }[] {
  const entries: { label: string; time: string }[] = [];
  if (row.checkIn) entries.push({ label: 'Check In', time: row.checkIn });
  (row.breaks || []).forEach((brk, index) => {
    entries.push({ label: `Break ${index + 1} Start`, time: brk.startAt ? formatTime12h(brk.startAt) : '--' });
    if (brk.endAt) entries.push({ label: `Break ${index + 1} End`, time: formatTime12h(brk.endAt) });
  });
  if (row.checkOut) entries.push({ label: 'Check Out', time: row.checkOut });
  return entries;
}

