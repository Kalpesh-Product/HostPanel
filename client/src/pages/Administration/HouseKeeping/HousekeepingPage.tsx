interface ErrorBoundaryProps {
  children: React.ReactNode;
}

interface ErrorBoundaryState {
  error: Error | null;
  errorInfo: React.ErrorInfo | null;
}

class HousekeepingErrorBoundary extends React.Component<ErrorBoundaryProps, ErrorBoundaryState> {
  constructor(props: ErrorBoundaryProps) {
    super(props);
    this.state = { error: null, errorInfo: null };
  }

  static getDerivedStateFromError(error: Error): Partial<ErrorBoundaryState> {
    return { error };
  }

  componentDidCatch(error: Error, errorInfo: React.ErrorInfo): void {
    this.setState({ errorInfo });
    console.error('[HousekeepingPage] render error:', error, errorInfo);
  }

  render(): React.ReactNode {
    if (this.state.error) {
      return (
          <div className="p-2 lg:p-2.5 min-h-full text-[#0F172A] font-sans text-[12px]">
            <PageFrame>
              <div className="mx-auto max-w-4xl rounded-[2rem] border border-red-200 bg-white p-6 shadow-sm">
                <div className="flex items-start gap-4">
                  <div className="rounded-2xl bg-red-50 p-3 text-red-600">
                    <ShieldAlert size={28} />
                  </div>
                  <div className="flex-1">
                    <h1 className="text-2xl font-pmedium tracking-tight text-red-900">
                      Housekeeping crashed while rendering
                    </h1>
                    <p className="mt-2 text-sm font-pmedium text-slate-600">
                      The page hit a render-time error. The details below should help us identify the
                      cause immediately.
                    </p>
                  </div>
                </div>

                <div className="mt-6 rounded-2xl border border-red-100 bg-red-50 p-4">
                  <p className="text-[10px] font-pmedium uppercase tracking-widest text-red-600">
                    Error message
                  </p>
                  <p className="mt-2 text-sm font-pmedium text-red-900">
                    {this.state.error?.message || 'Unknown error'}
                  </p>
                </div>

                {this.state.error?.stack ? (
                  <div className="mt-4 rounded-2xl border border-slate-200 bg-slate-50 p-4">
                    <p className="text-[10px] font-pmedium uppercase tracking-widest text-slate-500">
                      Stack trace
                    </p>
                    <pre className="mt-2 overflow-auto whitespace-pre-wrap break-words text-[11px] leading-relaxed text-slate-700">
                      {this.state.error.stack}
                    </pre>
                  </div>
                ) : null}

                {this.state.errorInfo?.componentStack ? (
                  <div className="mt-4 rounded-2xl border border-slate-200 bg-slate-50 p-4">
                    <p className="text-[10px] font-pmedium uppercase tracking-widest text-slate-500">
                      Component stack
                    </p>
                    <pre className="mt-2 overflow-auto whitespace-pre-wrap break-words text-[11px] leading-relaxed text-slate-700">
                      {this.state.errorInfo.componentStack}
                    </pre>
                  </div>
                ) : null}
              </div>
            </PageFrame>
          </div>
      );
    }

    return this.props.children;
  }
}

