  async function saveTask(event: React.FormEvent): Promise<void> {
    event.preventDefault();
    setTaskFormError('');
    try {
      const assigneeEmployeeProfileId = selectedStaff ? taskForm.assigneeEmployeeProfileId : null;

      // A staff member can't run two daily tasks at once — recurring
      // ("Repeats daily") tasks need at least a 30-minute gap from that same
      // staff member's other active recurring tasks. One-off "additional"
      // tasks (isRecurring off) are exempt and can be any time.
      if (taskForm.isRecurring && assigneeEmployeeProfileId && taskForm.startTaskTime) {
        const newMinutes = parseTimeToMinutes(taskForm.startTaskTime);
        const conflict = tasks.find((t) => {
          if (t.id === editingTask?.id) return false;
          if (t.sourceType === 'booking' || !t.isRecurring || t.status === 'Cancelled') return false;
          if (t.assigneeEmployeeProfileId !== assigneeEmployeeProfileId) return false;
          const existingMinutes = parseTimeToMinutes(t.startTaskTime);
          if (newMinutes === null || existingMinutes === null) return false;
          const diff = Math.abs(existingMinutes - newMinutes);
          return Math.min(diff, 1440 - diff) < MIN_RECURRING_TASK_GAP_MINUTES;
        });
        if (conflict) {
          setTaskFormError(
            `${selectedStaff?.fullName || 'This staff member'} already has "${conflict.taskName}" at ${formatTime12h(conflict.startTaskTime || '')} — daily tasks need at least a ${MIN_RECURRING_TASK_GAP_MINUTES}-minute gap.`,
          );
          return;
        }
      }

      const taskName = taskForm.taskType === 'Custom' ? taskForm.taskName : taskForm.taskType;
      const payload = {
        taskName,
        taskType: taskForm.taskType,
        location: taskForm.location,
        floor: taskForm.floor,
        wing: taskForm.wing,
        assignedTo: selectedStaff?.fullName || (editingTask ? 'Unassigned' : taskForm.assignedTo || 'Unassigned'),
        assigneeEmployeeProfileId,
        startTaskTime: taskForm.startTaskTime,
        timeSlotLabel: taskForm.startTaskTime,
        status: editingTask ? taskForm.status : 'Pending',
        sourceType: 'manual',
        isAutoGenerated: false,
        isRecurring: taskForm.isRecurring,
      };
      setIsSavingTask(true);
      if (editingTask?.id) { await updateHousekeepingTask(editingTask.id, payload); }
      else { await createHousekeepingTask(payload); }
      setIsTaskModalOpen(false);
      setEditingTask(null);
      setTaskForm(taskFormState());
      setTaskFormError('');
      await refreshOverview();
    } catch (error: any) {
      setTaskFormError(error?.response?.data?.message || error?.message || 'Failed to save task.');
    } finally {
      setIsSavingTask(false);
    }
  }

